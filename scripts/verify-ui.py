from pathlib import Path
from playwright.sync_api import sync_playwright
root = Path(__file__).resolve().parents[1]
url = (root / "scratch/preview/url.txt").read_text().strip()
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={"width": 1440, "height": 1100}, device_scale_factor=1)
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto(url)
    page.get_by_text("Connected locally", exact=True).wait_for()
    page.get_by_role("button", name="Review the checkout flow", exact=False).click()
    page.get_by_role("heading", name="Review the checkout flow", level=2, exact=True).wait_for()
    page.locator("#run-agent").select_option("codex")
    page.get_by_role("button", name="Preview context", exact=True).click()
    page.get_by_role("heading", name="Context preview", exact=True).wait_for()
    assert "Handoff record" in page.locator("#preview-text").inner_text()
    assert "Keep the public API stable" in page.locator("#preview-text").inner_text()
    page.locator("#close-preview").click()
    page.get_by_role("button", name="+ New task", exact=True).click()
    page.locator("#new-title").fill("UI verification task")
    page.locator("#new-project").fill(str(root / "scratch/preview"))
    page.locator("#new-prompt").fill("Sample task for UI verification only. Do not launch an agent.")
    page.locator("#create-only").click()
    page.get_by_role("heading", name="UI verification task", level=2, exact=True).wait_for()
    page.get_by_role("button", name="Review the checkout flow", exact=False).click()
    page.get_by_role("heading", name="Review the checkout flow", level=2, exact=True).wait_for()
    page.screenshot(path=str(root / "scratch/dashboard-desktop.png"), full_page=True)
    assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
    page.set_viewport_size({"width": 390, "height": 844})
    page.screenshot(path=str(root / "scratch/dashboard-mobile.png"), full_page=True)
    assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
    assert not errors, errors
    print("Browser QA passed: task selection, handoff preview, task creation, desktop/mobile layout, no browser errors.")
    browser.close()
